func TestMigrate(t *testing.T) {
	tmpdir := t.TempDir()
	v2File := path.Join(tmpdir, "v2_config.yml")
	v3File := path.Join(tmpdir, "v3_config.yml")

	require.NoError(t, os.WriteFile(v2File, []byte(v2ConfigExample), 0o600))
	require.NoError(t, run(context.Background(), v2File, v3File))

	b, err := os.ReadFile(v3File)
	require.NoError(t, err)
	assert.Equal(t, expectedV3Conf, string(b))
}

func TestCheckDeprecatedTemplateVariables(t *testing.T) {
	for _, tt := range []struct {
		name     string
		conf     V2Config
		expected []string
	}{
		{
			name: "PackagePath",
			conf: V2Config{Dir: addr("mocks/{{ .PackagePath | base }}")},
			expected: []string{
				"PackagePath template variable has been deleted. Use \"{{ .SrcPackagePath }}\" instead",
			},
		},
		{
			name: "MockName",
			conf: V2Config{FileName: addr("{{ .MockName | snakecase }}.go")},
			expected: []string{
				"MockName template variable has been deleted. Use \"{{ .StructName }}\" instead",
			},
		},
		{
			name: "PackageName and PackagePath",
			conf: V2Config{
				Dir:    addr("mocks/{{ .PackagePath }}"),
				Outpkg: addr("mock{{ .PackageName }}"),
			},
			expected: []string{
				"PackageName template variable has been deleted. Use \"{{ .SrcPackageName }}\" instead",
				"PackagePath template variable has been deleted. Use \"{{ .SrcPackagePath }}\" instead",
			},
		},
		{
			name: "InterfaceNameLowerCamel is not reported as InterfaceNameLower",
			conf: V2Config{FileName: addr("{{ .InterfaceNameLowerCamel }}.go")},
			expected: []string{
				"InterfaceNameLowerCamel template variable has been deleted. Use \"{{ .InterfaceName | camelcase | firstLower }}\" instead",
			},
		},
		{
			name:     "v3 variables",
			conf:     V2Config{Dir: addr("mocks/{{ .SrcPackagePath }}/{{ .SrcPackageName }}")},
			expected: []string{},
		},
	} {
		t.Run(tt.name, func(t *testing.T) {
			tbl := newTableWriter(context.Background())
			checkDeprecatedTemplateVariables(context.Background(), &tt.conf, tbl)

			messages := make([]string, 0, len(tbl.seenMessages))
			for msg := range tbl.seenMessages {
				messages = append(messages, msg)
			}
			assert.ElementsMatch(t, tt.expected, messages)
		})
	}
}

func TestMigrateRenamedTemplateVariables(t *testing.T) {
	for _, tt := range []struct {
		name     string
		conf     V2Config
		expected config.Config
	}{
		{
			name: "PackageName in outpkg",
			conf: V2Config{Outpkg: addr("{{.PackageName}}_test")},
			expected: config.Config{
				PkgName: addr("{{.SrcPackageName}}_test"),
			},
		},
		{
			name: "PackagePath and MockName in dir",
			conf: V2Config{Dir: addr("mocks/{{ .PackagePath }}/{{ .MockName | snakecase }}")},
			expected: config.Config{
				Dir: addr("mocks/{{ .SrcPackagePath }}/{{ .StructName | snakecase }}"),
			},
		},
		{
			name: "PackageName in mockname",
			conf: V2Config{MockName: addr("Mock{{.PackageName | firstUpper}}{{.InterfaceName}}")},
			expected: config.Config{
				StructName: addr("Mock{{.SrcPackageName | firstUpper}}{{.InterfaceName}}"),
			},
		},
		{
			name: "v3 variables are left alone",
			conf: V2Config{
				Dir:    addr("mocks/{{.SrcPackagePath}}"),
				Outpkg: addr("{{.SrcPackageName}}"),
			},
			expected: config.Config{
				Dir:     addr("mocks/{{.SrcPackagePath}}"),
				PkgName: addr("{{.SrcPackageName}}"),
			},
		},
	} {
		t.Run(tt.name, func(t *testing.T) {
			var v3Config *config.Config
			migrateConfig(context.Background(), newTableWriter(context.Background()), &tt.conf, &v3Config)

			require.NotNil(t, v3Config)
			assert.Equal(t, tt.expected, *v3Config)
		})
	}
}

func TestMigrateProfile(t *testing.T) {
	for _, tt := range []struct {
		name       string
		profile    *string
		cpuprofile *string
		expected   *string
	}{
		{
			name:     "profile",
			profile:  addr("mockery.prof"),
			expected: addr("mockery.prof"),
		},
		{
			name:       "cpuprofile",
			cpuprofile: addr("mockery.prof"),
			expected:   addr("mockery.prof"),
		},
		{
			// v2 used `profile` over `cpuprofile` when both were set.
			name:       "profile takes precedence over cpuprofile",
			profile:    addr("profile.prof"),
			cpuprofile: addr("cpuprofile.prof"),
			expected:   addr("profile.prof"),
		},
		{
			name:       "empty profile",
			profile:    addr(""),
			cpuprofile: addr("cpuprofile.prof"),
			expected:   addr("cpuprofile.prof"),
		},
	} {
		t.Run(tt.name, func(t *testing.T) {
			tbl := newTableWriter(context.Background())
			var v3Config *config.Config
			migrateConfig(
				context.Background(),
				tbl,
				&V2Config{Profile: tt.profile, Cpuprofile: tt.cpuprofile},
				&v3Config,
			)

			require.NotNil(t, v3Config.Cpuprofile)
			assert.Equal(t, *tt.expected, *v3Config.Cpuprofile)
			for msg := range tbl.seenMessages {
				assert.NotContains(t, msg, "`profile`")
			}
		})
	}
}
